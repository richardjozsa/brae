// NSRDS correlation forms + H2O coefficients vs OpenFOAM's OWN values.
//
// THE ORACLE IS OPENFOAM, NOT ARITHMETIC I DID MYSELF. The table below was produced by
// dissect/liqref -- a small OF program that constructs Foam::H2O and prints rho/mu/kappa/Cp/h at 17
// digits. Testing against hand-computed values would only prove I can evaluate my own formula; testing
// against OF proves the FORM and the COEFFICIENTS both match the thing brae has to reproduce.
//
// Range 280-400 K brackets squareBendLiq, which runs at a uniform 300 K.
//
// Includes a NEGATIVE CONTROL (see the end): a deliberately perturbed coefficient must fail these same
// assertions. A test that cannot go red is not a test.
#include "nsrds_functions.cuh"
#include <cstdio>
#include <cmath>
#include <vector>

using namespace brae;

namespace {

struct Row { double T, rho, mu, kappa, Cp, h; };

// Generated by: source $OFBASHRC && dissect/liqref/bin/liqref     (OpenFOAM v2412, p = 1e5 Pa)
const std::vector<Row> kOF = {
