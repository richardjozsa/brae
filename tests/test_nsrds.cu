};

int failures = 0;

// Relative agreement. 1e-13 is not a fit: both sides evaluate the same closed form in double, so the
// only difference available is the last couple of ulp from operation ordering.
void expectRel(const char* what, double T, double got, double want, double tol = 1e-13)
{
    const double rel = std::fabs(got - want)/std::fmax(std::fabs(want), 1e-300);
    if (!(rel <= tol))
    {
        std::printf("  FAIL %-6s T=%.0f  brae %.17g  OF %.17g  rel %.3e (tol %.0e)\n",
                    what, T, got, want, rel, tol);
        ++failures;
    }
}

}   // namespace

int main()
{
    std::printf("NSRDS forms + H2O coefficients vs OpenFOAM (dissect/liqref, v2412)\n");

    for (const Row& r : kOF)
    {
        expectRel("rho",   r.T, H2OLiquid::rho(r.T),   r.rho);
        expectRel("mu",    r.T, H2OLiquid::mu(r.T),    r.mu);
        expectRel("kappa", r.T, H2OLiquid::kappa(r.T), r.kappa);
        expectRel("Cp",    r.T, H2OLiquid::Cp(r.T),    r.Cp);
        expectRel("h",     r.T, H2OLiquid::h(r.T),     r.h);
    }
    std::printf("  %zu temperatures x 5 properties checked against OF\n", kOF.size());

    // ---------------------------------------------------------------------------------------------
    // h_ must be the analytic INTEGRAL of Cp_, i.e. dh/dT == Cp(T). This is the property that makes the
    // enthalpy consistent with the heat capacity, and it is the one a Newton he->T inversion CANNOT
    // check for itself: an h that is smooth and invertible but inconsistent with Cp converges happily
    // to a wrong temperature. Central difference, so the tolerance is the truncation error of the
    // difference (O(dT^2) on a 5th-order polynomial), not round-off.
    {
        const double dT = 1e-3;
        for (const Row& r : kOF)
        {
            const double dhdT = (H2OLiquid::h(r.T + dT) - H2OLiquid::h(r.T - dT))/(2*dT);
            expectRel("dh/dT=Cp", r.T, dhdT, H2OLiquid::Cp(r.T), 1e-9);
        }
        std::printf("  dh/dT == Cp(T) verified at every tabulated temperature\n");
    }

    // ---------------------------------------------------------------------------------------------
    // Physical sanity at the tutorial's operating point, so a sign slip or a units error that happened
    // to be self-consistent still gets caught. Water at 300 K, 1 bar.
    {
        const double T = 300;
        struct { const char* n; double got, lo, hi; } checks[] = {
            {"rho [kg/m3]",   H2OLiquid::rho(T),   990.0,  1000.0},
            {"mu [Pa s]",     H2OLiquid::mu(T),    8.0e-4, 9.5e-4},
            {"kappa [W/mK]",  H2OLiquid::kappa(T), 0.58,   0.63},
            {"Cp [J/kgK]",    H2OLiquid::Cp(T),    4150.0, 4220.0},
        };
        for (const auto& c : checks)
            if (!(c.got > c.lo && c.got < c.hi))
            {
                std::printf("  FAIL %s = %.6g, outside the physical range [%g, %g] for water at 300 K\n",
                            c.n, c.got, c.lo, c.hi);
                ++failures;
            }
        std::printf("  water at 300 K is physical (rho %.1f, mu %.3e, kappa %.3f, Cp %.0f)\n",
                    H2OLiquid::rho(T), H2OLiquid::mu(T), H2OLiquid::kappa(T), H2OLiquid::Cp(T));
    }

    // ---------------------------------------------------------------------------------------------
    // NEGATIVE CONTROL: prove the assertions above can fail. Perturb one coefficient of each form by a
    // relative 1e-9 -- far below anything a real transcription error would be -- and require that the
    // 1e-13 comparison rejects it. If any of these "passes", the tolerance is too loose to catch a typo
    // and the whole table above is decoration.
    {
        int caught = 0;
        const double T = 300;
        const double bad5 = nsrdsFunc5(98.343885*(1 + 1e-9), 0.30542, 647.13, 0.081, T);
        const double bad1 = nsrdsFunc1(-51.964*(1 + 1e-9), 3670.6, 5.7331, -5.3495e-29, 10, T);
        const double bad0 = nsrdsFunc0(-0.4267*(1 + 1e-9), 0.0056903, -8.0065e-06, 1.815e-09, 0, 0, T);
        const double ref5 = H2OLiquid::rho(T), ref1 = H2OLiquid::mu(T), ref0 = H2OLiquid::kappa(T);
        if (std::fabs(bad5 - ref5)/ref5 > 1e-13) ++caught;
        if (std::fabs(bad1 - ref1)/ref1 > 1e-13) ++caught;
        if (std::fabs(bad0 - ref0)/std::fabs(ref0) > 1e-13) ++caught;
        if (caught != 3)
        {
            std::printf("  FAIL negative control: only %d of 3 perturbed coefficients were detected --\n"
                        "       the tolerance cannot catch a transcription error, so the table above proves nothing\n",
                        caught);
            ++failures;
        }
        else
        {
            std::printf("  negative control: all 3 perturbed coefficients rejected (test can go red)\n");
        }
    }

    std::printf("test_nsrds: %d failures\n", failures);
    return failures ? 1 : 0;
}
